def get_all_places():
    return list(TOURIST_PLACES)


def get_place_by_id(place_id):
    if not place_id:
        return None
    target = str(place_id).strip().lower()
    for place in TOURIST_PLACES:
        if str(place.get("id", "")).strip().lower() == target or str(place.get("name", "")).strip().lower() == target:
            return place
    return None


def get_places_by_city(city, case_sensitive=False):
    if case_sensitive:
        return [p for p in TOURIST_PLACES if p["city"].lower() == city.lower()]
    return [p for p in TOURIST_PLACES if p["city"].lower() == city.lower()]


def normalize_place(place):
    """Return a clean JSON-serialisable dict without mutating the source."""
    return dict(place)


